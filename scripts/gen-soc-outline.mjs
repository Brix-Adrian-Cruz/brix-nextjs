// Regenerates the client-safe SOC outline from the lesson data so the two can never drift.
// Usage: node scripts/gen-soc-outline.mjs
import { writeFileSync } from "node:fs";
import { DAYS } from "../app/training/_data/soc/course.ts";

const WEEKS = [
  { n: 1, title: "Intake & abuse triage", sub: "Queue, tags, phishing, hijacking, Maintenance Mode" },
  { n: 2, title: "Legal & customer-facing", sub: "Reports, DMCA, trademark, scans, compliance" },
  { n: 3, title: "Threats, special cases & capstone", sub: "DDoS, compromise, legal-adjacent, edge cases" },
];

const OUTLINE = DAYS.map((d) => ({
  id: d.id, week: d.week, mins: d.mins, title: d.title, labs: d.lab.length, answers: d.quiz.map((q) => q.a),
}));

const out = `// Lightweight SOC course outline that is safe to import into Client Components.
// Generated by scripts/gen-soc-outline.mjs from soc/course.ts: do not edit by hand.
import type { Week, OutlineDay } from "../types.ts";

export const WEEKS: Week[] = ${JSON.stringify(WEEKS, null, 1)};

export const OUTLINE: OutlineDay[] = ${JSON.stringify(OUTLINE)};

export const TOTAL_DAYS = OUTLINE.length;
`;
writeFileSync(new URL("../app/training/_data/soc/outline.ts", import.meta.url), out);
console.log(`Wrote outline for ${OUTLINE.length} days`);
